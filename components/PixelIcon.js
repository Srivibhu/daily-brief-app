export default function PixelIcon({ name, size = 18 }) {
  const rows = ICONS[name] || []
  const w = Math.max(...rows.map(r => r.length), 1), h = rows.length || 1
  return (
    <svg className="pixel-icon" width={size} height={size * h / w} viewBox={`0 0 ${w} ${h}`} aria-hidden="true" shapeRendering="crispEdges">
      {rows.flatMap((r, y) => [...r].map((c, x) => c === '#' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" /> : null))}
    </svg>
  )
}
